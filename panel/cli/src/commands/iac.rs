use crate::client;
use crate::commands::db::rand_byte;
use serde_json::json;

pub(crate) fn urlenc(s: &str) -> String {
    s.replace('%', "%25")
        .replace(' ', "%20")
        .replace('&', "%26")
        .replace('=', "%3D")
        .replace('+', "%2B")
        .replace('#', "%23")
}

pub async fn cmd_export(token: &str, output: Option<&str>) -> Result<(), String> {
    let data = client::agent_get("/iac/export", token).await?;

    let yaml = serde_yaml_ng::to_string(&data)
        .map_err(|e| format!("Failed to serialize YAML: {e}"))?;

    // Add a header comment
    let header = "# DockPanel server configuration\n# Generated by: dockpanel export\n# Apply with:   dockpanel apply <file>\n\n";
    let content = format!("{header}{yaml}");

    match output {
        Some(path) => {
            std::fs::write(path, &content)
                .map_err(|e| format!("Failed to write {path}: {e}"))?;
            eprintln!("\x1b[32m✓\x1b[0m Exported to {path}");
        }
        None => {
            print!("{content}");
        }
    }

    Ok(())
}

pub async fn cmd_apply(token: &str, file: &str, dry_run: bool, email: Option<&str>) -> Result<(), String> {
    let yaml_content = std::fs::read_to_string(file)
        .map_err(|e| format!("Cannot read {file}: {e}"))?;

    let desired: serde_json::Value = serde_yaml_ng::from_str(&yaml_content)
        .map_err(|e| format!("Invalid YAML: {e}"))?;

    // Get current state
    let current = client::agent_get("/iac/export", token).await?;

    let mut plan_create = Vec::new();
    let mut plan_skip = Vec::new();
    let mut applied = 0;
    let mut errors = 0;

    // ── Databases ───────────────────────────────────────────────────
    let desired_dbs = desired["databases"].as_array();
    let current_db_names: Vec<&str> = current["databases"]
        .as_array()
        .map(|a| a.iter().filter_map(|d| d["name"].as_str()).collect())
        .unwrap_or_default();

    if let Some(dbs) = desired_dbs {
        for db in dbs {
            let name = db["name"].as_str().unwrap_or("");
            if name.is_empty() {
                continue;
            }
            let engine = db["engine"].as_str().unwrap_or("postgres");
            let port = db["port"].as_u64().unwrap_or(5432) as u16;

            // Match by name (strip "dockpanel-db-" prefix from current names)
            let exists = current_db_names.iter().any(|n| {
                n.strip_prefix("dockpanel-db-").unwrap_or(n) == name
            });

            if exists {
                plan_skip.push(format!("database: {name} (already exists)"));
                continue;
            }

            let desc = format!("database: {name} ({engine}, port {port})");

            if dry_run {
                plan_create.push(desc);
            } else {
                const CHARSET: &[u8] = b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
                let mut password = String::with_capacity(16);
                let mut entropy_error = None;
                for _ in 0..16 {
                    match rand_byte() {
                        Ok(b) => password.push(CHARSET[(b % 62) as usize] as char),
                        Err(e) => {
                            entropy_error = Some(e);
                            break;
                        }
                    }
                }

                if let Some(e) = entropy_error {
                    println!("\x1b[31m✗\x1b[0m Creating database {name}... failed to generate a random password: {e}");
                    errors += 1;
                } else {
                    print!("  Creating database {name}... ");
                    let body = json!({
                        "name": name,
                        "engine": engine,
                        "password": password,
                        "port": port,
                    });
                    match client::agent_post("/databases", &body, token).await {
                        Ok(_) => {
                            println!("\x1b[32m✓\x1b[0m (password: {password})");
                            applied += 1;
                        }
                        Err(e) => {
                            println!("\x1b[31m✗\x1b[0m ({e})");
                            errors += 1;
                        }
                    }
                }
            }
        }
    }

    // ── Docker Apps ─────────────────────────────────────────────────
    let desired_apps = desired["apps"].as_array();
    let current_app_names: Vec<String> = current["apps"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|app| {
                    app["name"].as_str().map(|n| {
                        n.strip_prefix("dockpanel-app-").unwrap_or(n).to_string()
                    })
                })
                .collect()
        })
        .unwrap_or_default();

    if let Some(apps) = desired_apps {
        for app in apps {
            let name = app["name"].as_str().unwrap_or("");
            if name.is_empty() {
                continue;
            }
            let template = app["template"].as_str().unwrap_or("");
            let port = app["port"].as_u64().unwrap_or(0) as u16;

            if current_app_names.iter().any(|n| n == name) {
                plan_skip.push(format!("app: {name} (already exists)"));
                continue;
            }

            let desc = format!("app: {name} (template: {template}, port {port})");

            if dry_run {
                plan_create.push(desc);
            } else {
                print!("  Deploying app {name}... ");
                let mut body = json!({
                    "template_id": template,
                    "name": name,
                    "port": port,
                });
                if let Some(domain) = app["domain"].as_str() {
                    body["domain"] = json!(domain);
                    if let Some(em) = email {
                        body["ssl_email"] = json!(em);
                    }
                }
                match client::agent_post("/apps/deploy", &body, token).await {
                    Ok(_) => {
                        println!("\x1b[32m✓\x1b[0m");
                        applied += 1;
                    }
                    Err(e) => {
                        println!("\x1b[31m✗\x1b[0m ({e})");
                        errors += 1;
                    }
                }
            }
        }
    }

    // ── Cron Jobs ───────────────────────────────────────────────────
    // Unlike databases/apps, crons DO reconcile on a real apply —
    // /crons/sync replaces every entry whose id it's given. So the dry-run plan
    // is wrong if it always calls every cron "to create": diff against what
    // /iac/export already reported as current, the same source every other
    // resource type in this function uses.
    let desired_crons = desired["crons"].as_array();
    let current_crons: std::collections::HashMap<&str, &serde_json::Value> = current["crons"]
        .as_array()
        .map(|a| a.iter().filter_map(|c| c["id"].as_str().map(|id| (id, c))).collect())
        .unwrap_or_default();

    if let Some(crons) = desired_crons {
        if !crons.is_empty() {
            if dry_run {
                for cron in crons {
                    let id = cron["id"].as_str().unwrap_or("-");
                    let schedule = cron["schedule"].as_str().unwrap_or("");
                    let command = cron["command"].as_str().unwrap_or("");
                    match current_crons.get(id) {
                        Some(existing)
                            if existing["schedule"].as_str() == Some(schedule)
                                && existing["command"].as_str() == Some(command) =>
                        {
                            plan_skip.push(format!("cron: {id} (already exists, unchanged)"));
                        }
                        Some(_) => {
                            plan_create.push(format!("cron: {id} (updated — {schedule} {command})"));
                        }
                        None => {
                            plan_create.push(format!("cron: {id} ({schedule} {command})"));
                        }
                    }
                }
            } else {
                print!("  Syncing {} cron job(s)... ", crons.len());
                match client::agent_post("/crons/sync", &json!(crons), token).await {
                    Ok(_) => {
                        println!("\x1b[32m✓\x1b[0m");
                        applied += 1;
                    }
                    Err(e) => {
                        println!("\x1b[31m✗\x1b[0m ({e})");
                        errors += 1;
                    }
                }
            }
        }
    }

    // ── Firewall ────────────────────────────────────────────────────
    // Exported for reference (export/import round-trips it) but never reconciled
    // here — apply has no create/update/delete logic for firewall rules at all.
    // Silently dropping it left a user who edits firewall rules in the exported
    // file and re-applies with no signal that nothing happened.
    if let Some(fw) = desired.get("firewall") {
        let rule_count = fw["rules"].as_array().map(|r| r.len()).unwrap_or(0);
        if rule_count > 0 {
            println!(
                "\x1b[33m!\x1b[0m This file has a firewall section ({rule_count} rule(s)) — \
                 `apply` does not create, update, or remove firewall rules. Manage them with \
                 `dockpanel security firewall` instead."
            );
        }
    }

    // ── Output ──────────────────────────────────────────────────────
    if dry_run {
        println!("\x1b[1mPlan:\x1b[0m");
        if plan_create.is_empty() && plan_skip.is_empty() {
            println!("  No changes needed.");
        } else {
            for item in &plan_create {
                println!("  \x1b[32m+\x1b[0m {item}");
            }
            for item in &plan_skip {
                println!("  \x1b[90m=\x1b[0m {item}");
            }
            println!(
                "\n{} to create, {} existing",
                plan_create.len(),
                plan_skip.len()
            );
        }
    } else {
        println!();
        if errors > 0 {
            println!(
                "\x1b[33m{applied} applied, {errors} failed\x1b[0m"
            );
        } else if applied > 0 {
            println!("\x1b[32m{applied} applied\x1b[0m");
        } else {
            println!("No changes needed.");
        }
    }

    if errors > 0 {
        Err(format!("{errors} operation(s) failed"))
    } else {
        Ok(())
    }
}
